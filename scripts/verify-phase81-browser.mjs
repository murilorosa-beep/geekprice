import fs from "node:fs";
import assert from "node:assert/strict";
import { chromium } from "playwright";

const fixture = JSON.parse(fs.readFileSync(".tools/phase81-fixtures.json", "utf8"));
if (!/^geekprice_phase81_test_\d+$/.test(fixture.database)) throw new Error("Isolated fixtures required");
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const results = [];
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const origin = "http://127.0.0.1:3108";
page.setDefaultTimeout(45_000);
try {
  await page.goto(origin + "/login");
  await page.getByLabel("E-mail", { exact: true }).fill(fixture.emailA);
  await page.getByLabel("Senha", { exact: true }).fill(fixture.password);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await page.waitForURL("**/dashboard");
  const session = await (await page.request.get(origin + "/api/auth/session")).json();
  assert.equal(session.user.organizationId, fixture.orgA);
  results.push("Browser login with real PostgreSQL user");
  for (const route of ["/dashboard", "/products", "/recommendations", "/alerts", "/market", "/settings"]) {
    await page.goto(origin + route);
    console.log("Checking browser route " + route);
    await page.locator("h1").first().waitFor();
    assert.equal(new URL(page.url()).pathname, route);
    assert(!(await page.locator("body").innerText()).includes("Application error"));
    results.push("Browser navigation " + route);
  }
  await page.goto(origin + "/products");
  await page.getByRole("button", { name: /Cadastrar produto|Novo produto|Novo item/ }).first().click();
  const name = "TESTE_SINTETICO BROWSER " + Date.now();
  const form = page.locator("form").filter({ has: page.getByRole("button", { name: "Salvar produto" }) });
  await form.getByLabel("Nome", { exact: true }).fill(name);
  await form.getByLabel("Categoria", { exact: true }).fill("TESTE_SINTETICO");
  await form.getByLabel("SKU", { exact: true }).fill(name);
  await form.getByLabel("Custo de aquisição").fill("60");
  await form.getByLabel("Preço de venda").fill("110");
  await form.getByLabel("Quantidade", { exact: true }).fill("1");
  const saved = page.waitForResponse(r => r.url().endsWith("/api/inventory") && r.request().method() === "POST");
  await form.getByRole("button", { name: "Salvar produto" }).click();
  const savedResponse = await saved;
  assert.equal(savedResponse.status(), 201);
  const createdItem = await savedResponse.json();
  results.push("Browser inventory registration persisted");
  await page.goto(origin + "/market");
  const csv = `produto,idioma,condicao,acabamento,fonte,tipo_preco,moeda,valor,data_referencia\n${name},pt-BR,new,standard,TESTE_SINTETICO BROWSER PRIVATE,reference,BRL,120,${new Date().toISOString()}\n${name},pt-BR,new,standard,TESTE_SINTETICO BROWSER PRIVATE,reference,BRL,118,${new Date(Date.now() - 86_400_000).toISOString()}`;
  await page.getByLabel("Arquivo CSV BRL", { exact: true }).setInputFiles({ name: "TESTE_SINTETICO.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  const button = page.getByRole("button", { name: "Confirmar importacao BRL" });
  await button.waitFor();
  const imported = page.waitForResponse(r => r.url().endsWith("/partner-import/commit"));
  await button.click();
  assert.equal((await imported).status(), 201);
  await page.getByText(/2 novas cotacoes BRL registradas/).waitFor();
  results.push("Browser BRL upload, preview and confirmation persisted");
  await page.goto(origin + "/market");
  await page.getByText("Fonte privada não verificada", { exact: false }).first().waitFor();
  await page.getByText("Referência informada", { exact: false }).first().waitFor();
  results.push("Browser identifies private source and price type");
  await page.goto(origin + "/recommendations");
  await page.getByPlaceholder("Buscar por carta, coleção ou SKU...").fill(name);
  const productRow = page.locator("tr").filter({ hasText: name });
  const applied = page.waitForResponse(r => r.url().endsWith("/api/autopilot/apply"));
  await productRow.getByRole("button", { name: "Aplicar", exact: true }).click();
  const applyResponse = await applied; assert.equal(applyResponse.status(), 200);
  const batch = (await applyResponse.json()).batch;
  const appliedInventory = await (await page.request.get(origin + "/api/inventory?pageSize=100")).json();
  assert.notEqual(appliedInventory.items.find(i => i.id === createdItem.id).currentPrice, 110);
  results.push("Browser supervised price approval persists and audits");
  await page.getByRole("button", { name: /Histórico de Lotes & Rollback/ }).click();
  const newestBatch = page.locator("tbody tr").first();
  page.once("dialog", dialog => dialog.accept());
  const reverted = page.waitForResponse(r => r.url().endsWith("/api/autopilot/rollback") && r.request().method() === "POST");
  await newestBatch.getByRole("button", { name: "Desfazer (Rollback)" }).click();
  const revertedResponse = await reverted; assert.equal(revertedResponse.status(), 200);
  assert.equal((await revertedResponse.json()).batch.id, batch.id);
  const revertedInventory = await (await page.request.get(origin + "/api/inventory?pageSize=100")).json();
  assert.equal(revertedInventory.items.find(i => i.id === createdItem.id).currentPrice, 110);
  await page.getByText("Revertido", { exact: true }).first().waitFor();
  results.push("Browser rollback restores original synthetic price");
  await page.goto(origin + "/dashboard");
  const history = await (await page.request.get(origin + "/api/market/history?days=30")).json();
  assert.equal(history.hasData, true);
  await page.getByRole("heading", { name: "Histórico e Posicionamento de Preços" }).waitFor();
  await page.screenshot({ path: ".tools/phase81-dashboard.png", fullPage: true });
  assert.deepEqual(errors, []);
  results.push("Browser dashboard history from PostgreSQL without page errors");
  fs.writeFileSync(".tools/phase81-browser-results.json", JSON.stringify({ at: new Date().toISOString(), database: fixture.database, results, errors }, null, 2));
  console.log(JSON.stringify({ passed: results, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: ".tools/phase81-browser-failure.png", fullPage: true });
  console.error({ failedAt: new URL(page.url()).pathname, pageErrors: errors });
  throw error;
} finally {
  await browser.close();
}
